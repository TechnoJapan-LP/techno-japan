#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readImageSize, readImageSizeBuffer } from './lib/image-size.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LP_DIR = path.join(ROOT, 'LP');
const IMAGES_DIR = path.join(LP_DIR, 'images');
const OUT = path.join(LP_DIR, 'image-dimensions.js');
const JSON_OUT = path.join(LP_DIR, 'image-dimensions.json');
const EXTENSIONS = new Set(['.webp', '.png', '.jpg', '.jpeg']);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]
  );
}

const dimensions = {};
for (const file of walk(IMAGES_DIR).sort()) {
  if (!EXTENSIONS.has(path.extname(file).toLowerCase())) continue;
  const key = path.relative(LP_DIR, file).split(path.sep).join('/');
  const { width, height } = readImageSize(file);
  dimensions[key] = [width, height];
}

// 記事本文に残る外部画像も、推測値ではなく配信実体のバイト列から寸法を得る。
// 取得不能時に黙って属性を欠落させるとB3が再発するため、ビルドを失敗させる。
const dataSource = fs.readFileSync(path.join(LP_DIR, 'data.js'), 'utf8');
const remoteUrls = [...new Set([...dataSource.matchAll(/<img\b[^>]*\bsrc=["'](https?:\/\/[^"']+)["']/gi)].map((match) => match[1]))].sort();
for (const url of remoteUrls) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`外部画像を取得できません (${response.status}): ${url}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  const { width, height } = readImageSizeBuffer(buffer, url);
  dimensions[url] = [width, height];
}

const output = `/* Generated by scripts/build-image-dimensions.mjs from LP/images. */
(function(){
  const sizes=${JSON.stringify(dimensions)};
  window.tjImageDimensions=function(src){
    const key=String(src||'').split(/[?#]/)[0].replace(/^\\/+/, '');
    return sizes[key]||null;
  };
  window.tjImageSizeAttrs=function(src){
    const size=window.tjImageDimensions(src);
    return size?'width="'+size[0]+'" height="'+size[1]+'"':'';
  };
})();
`;
/* 中身が変わったら、参照側の ?v も一緒に上げる。

   sw.js は JS を cache-first で扱うので、?v が据え置きだと一度訪れた
   ブラウザには新しい寸法表が永久に届かない（AUDIT §9-11）。
   このファイルは LP/images/ の中身から作られ、その images は
   sync-drive-images.yml が2時間おきに Drive から取ってくる。
   つまり**人が触っていなくても勝手に変わる**生成物で、
   そのたびに手で ?v を上げるのは運用として続かない。
   実際 2026-08-06 に、画像3枚が同期された直後の CI が
   「?v が据え置き」で落ちた。生成した側が上げる。 */
function bumpAssetVersion(assetName) {
  const re = new RegExp(`(${assetName.replace('.', '\\.')})\\?v=(\\d+)`, 'g');
  const files = [];
  (function walkHtml(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name);
      if (entry.isDirectory()) walkHtml(p);
      else if (entry.name.endsWith('.html')) files.push(p);
    }
  })(LP_DIR);

  // 参照されている最大値の次を全参照に揃える。
  // ファイルごとに +1 すると、混在（§9-44 E の detail.css）が起きる。
  let max = 0;
  const seen = [];
  for (const f of files) {
    const text = fs.readFileSync(f, 'utf8');
    if (!re.test(text)) { re.lastIndex = 0; continue; }
    re.lastIndex = 0;
    seen.push(f);
    for (const m of text.matchAll(re)) max = Math.max(max, Number(m[2]));
  }
  if (!seen.length) return null;
  const next = max + 1;
  for (const f of seen) {
    const text = fs.readFileSync(f, 'utf8');
    fs.writeFileSync(f, text.replace(re, `$1?v=${next}`));
  }
  return { next, count: seen.length };
}

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (current !== output) {
  fs.writeFileSync(OUT, output);
  const bumped = current ? bumpAssetVersion('image-dimensions.js') : null;
  if (bumped) {
    console.log(`  image-dimensions.js の中身が変わったので ?v=${bumped.next} へ更新（${bumped.count} ファイル）`);
  }
}
const jsonOutput = JSON.stringify(dimensions, null, 2) + '\n';
const currentJson = fs.existsSync(JSON_OUT) ? fs.readFileSync(JSON_OUT, 'utf8') : '';
if (currentJson !== jsonOutput) fs.writeFileSync(JSON_OUT, jsonOutput);
console.log(`Image dimensions: ${Object.keys(dimensions).length} images (${remoteUrls.length} remote) → ${path.relative(ROOT, OUT)} (${Buffer.byteLength(output)} bytes)`);
